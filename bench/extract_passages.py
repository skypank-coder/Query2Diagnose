"""Split downloaded sources into citable passages and write LICENSES.md.

Each heading (any level) on an iFixit page starts a passage; its ID is
`ifx-<wikiid>-<slug of heading path>`, which stays stable while iFixit keeps
the heading. Link-list sections are dropped. Public-domain pages give one
passage per kept section.

Run with `python -I -m bench.extract_passages`.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from core.paths import LICENSES_FILE, PASSAGES_FILE, SOURCES_RAW

SKIP_SECTIONS = {
    "related pages",
    "additional resources",
    "questions other people have asked related to this",
    "similar guides and wikis",
}

# [tag|target|visible text|options] elements that keep their visible text;
# every other tag (image, video, wikilist, ...) is dropped.
_TEXT_TAGS = {"guide", "parts", "product", "post", "link", "document"}


def _inline(match: re.Match) -> str:
    tag, fields = match.group(1), match.group(2).split("|")
    if tag not in _TEXT_TAGS or len(fields) < 2 or "=" in fields[1]:
        return ""
    return fields[1]


def clean_markup(raw: str) -> str:
    text = raw.replace(" ", " ").replace("\r\n", "\n")
    text = re.sub(r"\[comment\].*?\[/comment\]", "", text, flags=re.S)
    text = re.sub(r"\{table.*?\n\}", "", text, flags=re.S)
    text = re.sub(r"\+\+(.*?)\+\+", r"\1", text)
    text = re.sub(r"\[/?(quote|note)(\|[^\]]*)?\]", "", text)
    text = re.sub(r"\[\[([^\]|]+)\|([^\]|]+)(\|[^\]]*)?\]\]", r"\2", text)
    text = re.sub(r"\[\[([^\]|]+)\]\]", r"\1", text)
    text = re.sub(r"\[([a-z_]+)\|([^\]]*)\]", _inline, text)
    text = re.sub(r"\[([a-z_]+)\]", "", text)
    text = text.replace("***", "").replace("'''", "").replace("''", "")
    lines = []
    for line in text.split("\n"):
        m = re.match(r"^(\*+)\s*(.*)$", line)
        if m:
            line = "  " * (len(m.group(1)) - 1) + "- " + m.group(2)
        lines.append(line.rstrip())
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def slugify(text: str) -> str:
    text = text.lower().replace("’", "").replace("'", "")
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def ifixit_passages(record: dict) -> list[dict]:
    raw = record["contents_raw"]
    heading_re = re.compile(r"^(={2,})\s*(.*?)\s*=+\s*$", re.M)
    blocks: list[tuple[list[str], str]] = []
    path: list[str] = []
    last = 0
    for m in heading_re.finditer(raw):
        blocks.append((list(path), raw[last:m.start()]))
        level = len(m.group(1)) - 2
        heading = clean_markup(m.group(2))
        path = path[:level] + [heading]
        last = m.end()
    blocks.append((list(path), raw[last:]))

    passages, seen = [], set()
    for path, body in blocks:
        if any(p.lower() in SKIP_SECTIONS for p in path):
            continue
        text = clean_markup(body)
        if not text:
            continue
        slug = "--".join(slugify(p) for p in path) or "intro"
        pid = base = f"ifx-{record['wikiid']}-{slug}"
        n = 2
        while pid in seen:
            pid, n = f"{base}-{n}", n + 1
        seen.add(pid)
        passages.append({
            "passage_id": pid,
            "source": "ifixit",
            "doc_title": record["display_title"],
            "section": " > ".join(path) or "(introduction)",
            "text": text,
            "url": record["url"],
            "revision": record["revisionid"],
            "license": record["license"],
            "n_words": len(text.split()),
        })
    return passages


def public_domain_passages(record: dict) -> list[dict]:
    return [{
        "passage_id": f"pd-{record['id']}-{slugify(heading)}",
        "source": "public_domain",
        "doc_title": record["title"],
        "section": heading,
        "text": text,
        "url": record["url"],
        "revision": record["html_sha256"][:12],
        "license": record["license"],
        "n_words": len(text.split()),
    } for heading, text in record["sections"].items()]


def _load(directory: Path) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(directory.glob("*.json"))]


def write_licenses(ifixit: list[dict], public: list[dict]) -> None:
    lines = [
        "# Source documents and licences",
        "",
        "Generated by `bench/extract_passages.py` from `data/sources/raw/`. Do not edit by hand.",
        "",
        "Policy: iFixit pages and U.S. public-domain pages only. No manufacturer manuals.",
        "",
        "## iFixit (CC BY-NC-SA 3.0)",
        "",
        "Licence: https://creativecommons.org/licenses/by-nc-sa/3.0/ — terms: https://www.ifixit.com/Info/Licensing",
        "Changes: markup and images removed; split into section-level passages.",
        "",
        "| Page | Revision | Accessed (UTC) | Authors |",
        "|---|---|---|---|",
    ]
    for r in ifixit:
        lines.append(f"| [{r['display_title']}]({r['url']}) | {r['revisionid']} | "
                     f"{r['fetched_at'][:10]} | {', '.join(r['authors'])} |")
    lines += ["", "## Public domain (U.S. federal government works)", "",
              "| Page | Publisher | Licence | Accessed (UTC) |", "|---|---|---|---|"]
    for r in public:
        lines.append(f"| [{r['title']}]({r['url']}) | {r['publisher']} | {r['license']} | "
                     f"{r['fetched_at'][:10]} |")
    LICENSES_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    ifixit = _load(SOURCES_RAW / "ifixit")
    public = _load(SOURCES_RAW / "public_domain")
    passages = [p for r in ifixit for p in ifixit_passages(r)]
    passages += [p for r in public for p in public_domain_passages(r)]
    with PASSAGES_FILE.open("w", encoding="utf-8", newline="\n") as f:
        for p in passages:
            f.write(json.dumps(p, ensure_ascii=False) + "\n")
    write_licenses(ifixit, public)
    print(f"{len(passages)} passages from {len(ifixit)} iFixit + {len(public)} public-domain pages "
          f"-> {PASSAGES_FILE.relative_to(PASSAGES_FILE.parents[2])}")


if __name__ == "__main__":
    main()
